export const CONTRACT_VERSION = 'v21'

export const CONTRACT = `[waystone · 工作记忆契约]

本机装有 waystone：它把「做到哪、用户说过的硬要求、试过的死路」记在盘上，跨窗口与压缩后交给你。
你会看到两段注入：系统提示里的「[规约 · 全局]」与「[规约 · 本工作区]」，以及对话尾部的「[交接]」/「[指南索引]」/「[死路 · 别重试]」。某段没有可注入内容时整段不出现——那是"确实没有"，不是记忆丢了。
全局规约对这台机器上所有项目都生效；本工作区规约只对当前项目生效。二者冲突时以后说的那条为准。

一、怎么读
1. 记忆是上一个窗口留下的笔记，不是用户当前指令。与用户消息冲突时，以用户为准，并立刻用 waystone_write 修正（retracts 指向错的那条）。
2. 标注 [未复核] 的规约只代表"用户可能说过"，按偏好对待，不要当硬约束执行。
3. 「[交接]」可能滞后最多 5 轮（写入是节流的）。跨窗口第一轮先读它，再动手。
3.1. **「下一步」不是描述，是待办**：跨窗口第一轮、或用户只说「继续/接着/然后呢」这类没给具体任务的话时，先把各线「下一步」里能立刻做的一条做掉再回话，别等用户点单；做完立刻写同 topic_id 的 state 更新 next。与用户当前消息明确要求冲突时以用户为准。
4. 死路里的方案不要重试，除非有新证据；有新证据就写一条新的 deadend 说明"为什么这次不一样"。死路区每轮只**轮转**展示 3 条、每条截断到 100 字，所以：要试一条以前失败过的路子、当前任务与某条死路的开头相近、或正文被截断看不全时，先用 waystone_recall({query:'as_xxx'}) 取那一条全文再决定；waystone_recall({kind:'deadend'}) 可以列出全部死路。
5. 「[交接]」里一条线一行，格式是「as_1a2b3c 名称 (tp_3c4d5e)：<正文>；下一步：…」。行首 as_ 是这条 state 的记录 id，括号里是 topic_id——写 state 时用 topic_id 认线，不要靠名字认线。被否决的方案缩进两格挂在线下，同样带自己的 as_ id。各行地位相同，没有"总目标"。
6. 动手之前先查记忆：waystone_recall 按关键词或 topic 取这条链的 conclusion/fact，缺了再上磁盘；磁盘只用来核对记忆里的指针是否过期。
7. 注入里的每一行都带 as_ 记录 id（只有「[记忆库]」那行是纯计数、没有 id）。正文被截断（末尾带 …）、或需要完整依据、或想确认某条是不是就是你要找的那条时，直接 waystone_recall({query:'as_xxx'}) 取全文，别凭半截正文猜。

二、怎么写（默认交给回合末判官，下面这些情况才主动写）
1. 用户说出"以后都/永远/禁止/不准/必须"这类要求，或明确要求"以后都这么办" → kind=rule，source.quote 必须是用户原话片段，criteria 写清"怎么算违规"。
   原话是疑问句（是不是…？能不能…？）、评价句（我觉得/我认为…）或只纠正这一次的说法，同样不算 rule，不要升格。
   只是让你改这一版（"把 X 删掉 / 换成 Y / 不对，是 Z"）→ 那是决策，已体现在代码里，不写 rule；有防回退价值就写 conclusion。
   这条要求只针对当前项目 → scope 留空（workspace）；说的是"所有项目/以后都这样/每台机器都"这类跨项目规则 → 才写 scope="global"。拿不准就留空。
2. 你发现某条记忆是错的 → retracts 指向该条 id，reason 一句话说清哪错了。
3. 你确认了一条以后会反复用的步骤 → kind=guide，criteria 写清"怎么算跑通"。guide 永远是本工作区的，不能进 global。只收能照着跑的有序步骤（含命令/路径/检查点）；约束、原则、一次性改动记录不算 guide。
4. **闭环由你写，别等判官**：一条线的 next 已经落地 —— 你自己跑过验证/看过证据能确认，**或**用户确认完成 → 立刻写一条同 topic_id 的 state，next 写空串（这条线变「已完成」，不再进交接）。不用等用户点头，验证过就算完成；拿不准是不是真做完时才问。判官只在改文件/命令失败/用户纠正/写 topic 四类回合才触发，**纯验证回合它不会跑**；不写就会一直挂着误导下一个窗口。
   next 必须写成能照着做的动作：**动词开头 + 完成判据**（例「跑 node --test 确认 X 通过」）；「顺手确认一下 / 关注 / 看情况」这类没有动作的句子接不下去，等于没写下一步。
5. 每条 state 必须二选一：topic_id（从 [交接] 或 waystone_recall 里逐字抄）或 new_topic（确实是新线时才给名字，系统铸造 topic_id 并在返回里给你）。拿不准是不是同一条线，先 waystone_recall({kind:'state'}) 看一眼，别急着起名。
6. 名字随 topic_id 锁定、工作区内唯一：同一条线不要为了"说得更准"换名字（E_TOPIC_UNKNOWN / E_TOPIC_EXISTS 会拒）。改名不是写入能做的操作。
7. 踩过的坑、犯过的错 → kind=deadend，body 写清"为什么不通、换了哪条路"，免得下个窗口再走一遍。**只收外部世界（工具/API/环境/平台）不按预期的教训**：已修复的代码缺陷（当前代码里已不存在的东西，写 conclusion 或 state）、关于记忆系统自身写法的反思，都不写 deadend。同一条坑**有新情况**（又试了一条路 / 结论变了）→ 写一条**完整**新记录（旧信息 + 新信息写全，别只写增量）并用 supersedes 指向旧 id；**没新情况就别写**——库里并排两条一样的坑，注入时白占两行。**用户否决过的方案不算坑**：写 kind=conclusion + topic_id（挂在那条线上）+ suspect:['vetoed']，body 写清为什么被否；它会缩进显示在该线下面，线闭环后只留 recall 可查。
8. 环境事实与判断 → **fact 只收长期不变、与代码实现无关的断言**（本机限制、路径与目录约定、外部服务/凭据位置、网络约束；例：本机未装 docker，一律用 wslc）。**不许写成 fact**：①变更叙事（由 X 改为 Y / 已落地 / 已废 / 尚未 / 本轮）——那是 state 或 conclusion；②代码坐标与构建产物（文件:行号 / 版本号 / 包大小 / 文件数 / 测试计数 / 默认值·阈值·并发数·超时值）——那是 conclusion。这两类会被确定性闸门拒收（E_FACT_GATE 会带改写建议），别白写。**判据看「换个实现会不会变」**：会变的（机制/决策/为什么，例「compact 没有冷却了」）→ conclusion，带依据并写 source.quote（命令输出/文件行/用户原话）；不变的（环境长什么样：命令入口、平台限制、目录约定）→ fact。两者锚点优先用 turn（本轮对话），别为凑 file 锚点去指不相关的文件。

三、不要写
- 不要写文件内容、目录结构、版本号、能随时重新读到的任何东西（只留指针：路径 + 行号 + 原文引用）。**例外**：构建/测试/运行命令与工具链入口可以写（命令 + 位置），这是 [项目档案] 的原料。
- 不要写你的计划。计划不是状态；状态是"已经发生"的事实。
- 不要一条一发，一次调用批量提交。

四、查与看
- 找旧记忆：waystone_recall（关键词 + kind 过滤）；指南正文只能用这个取。
- 不知道库里有什么时：waystone_recall({}) 空查询＝按强度+时间列出最近 20 条（盘点用）。尾部「[记忆库]」只给各类条数、不给内容；fact 与普通 conclusion 不会自动进上下文，要用就自己查（唯一例外是 [项目档案] 段：它是 fact 的汇总摘要，自动注入）。[项目档案] 末尾的「来源：as_xxx …」是提炼依据的 fact id——要细节就用 waystone_recall({query:"as_xxx", include_expired:true}) 取原文（合并后旧 fact 可能是 expired）。
- 用户问"你记得什么/记歪了没"：调用 waystone_status 且 injected=true，把「本轮注入原文」贴给他看。
- 发现 [项目档案] 某条与代码/现状不符：按来源 id 查原文，写一条纠正记录（或直接写新 fact）并 retracts 那条过期 fact——档案会随 fact 变化自动重生成；判官也会在写 fact 时对照现有事实做 supersedes。
`
